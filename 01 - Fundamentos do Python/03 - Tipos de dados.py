'''
Em python existe 4 tipos de dados ou tipos primitivos que são: inteiro (int) que representa os números inteiros, real (float) que representa os números flutuante ou números quebrados ou seja números com vírgulas, caracteres ou string (str) que representam os texto, booleanos (True e False) o tipo booleanos só aceita dois valores verdadeiro ou falso
'''

inteiro = 30 # no tipo inteiro são passados apenas os números inteiros
print(inteiro)
real = 10.3 # no tipo real são passados apenas os número reais
print(real)
caracter = 'Olá, mundo!' # no tipo caracteres são passados apenas os caracteres ou seja texo, tudo que tiver dentro das aspas simples e duplas é um caracter
print(caracter)
texto = '123456'
print(type(texto))
verdadeiro = True # no tipo booleanos são passados apenas dois valores o verdadeiro e o falso
print(verdadeiro)
falso = False # no tipo booleanos são passados apenas dois valores o verdadeiro e o falso
print(falso)