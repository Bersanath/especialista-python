'''
    Operadores de atribuição em Python são símbolos usados para atribuir valores a variáveis, sendo o mais comum o =. Existem também os operadores de atribuição composta (ou atribuição aumentada) como +=, -=, *=, /=, que combinam uma operação aritmética com a atribuição, como x += 2 que é o mesmo que x = x + 2, tornando o código mais conciso e legível, além do operador := (operador morsa) introduzido no Python 3.8 para atribuir e usar o valor em uma mesma expressão. 
    
'''
x = 3

x += 2
print(x)

x /= 2

print(x)

x *= 2
print(x)

x -= 2   
print(x)

c = x - 2
print(c)